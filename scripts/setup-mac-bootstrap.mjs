#!/usr/bin/env node

import { createHash } from "node:crypto";
import { constants as fsConstants } from "node:fs";
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import { spawn } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lockfile = join(repositoryRoot, "package-lock.json");
const nodeModules = join(repositoryRoot, "node_modules");
const stamp = join(nodeModules, ".codex-pad-lock-sha256");

async function exists(path) {
  try {
    await access(path, fsConstants.F_OK);
    return true;
  } catch {
    return false;
  }
}

function run(executable, arguments_) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(executable, arguments_, {
      cwd: repositoryRoot,
      stdio: "inherit",
      env: process.env,
    });
    child.once("error", reject);
    child.once("exit", (code, signal) => {
      if (code === 0) resolvePromise();
      else reject(new Error(`${executable} ${arguments_.join(" ")} failed${signal ? ` with signal ${signal}` : ` with exit code ${code ?? "unknown"}`}.`));
    });
  });
}

if (process.platform !== "darwin") {
  throw new Error("Codex Pad background setup is supported only on macOS.");
}

const lockDigest = createHash("sha256").update(await readFile(lockfile)).digest("hex");
let installedDigest = "";
try {
  installedDigest = (await readFile(stamp, "utf8")).trim();
} catch {
  // A clean clone has no dependency stamp.
}

if (!(await exists(nodeModules)) || installedDigest !== lockDigest) {
  await run("npm", ["ci"]);
  await mkdir(nodeModules, { recursive: true });
  await writeFile(stamp, `${lockDigest}\n`, { encoding: "utf8", mode: 0o600 });
}

await run("npm", ["run", "build"]);
// Installed-version schemas are a read-only description generated by the
// bundled Codex binary into Nerva-owned Application Support. Make the normal
// one-command setup produce that compatibility proof automatically.
await run(process.execPath, [
  join(repositoryRoot, "apps", "bridge", "dist", "cli.js"),
  "setup",
  "--generate-schemas",
]);
await run(process.execPath, [
  join(repositoryRoot, "apps", "bridge", "dist", "cli.js"),
  "setup-mac",
  ...process.argv.slice(2),
]);
